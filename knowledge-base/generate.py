"""Generate the knowledge-base Markdown indexes from the chat archive.

The source of truth is ``data/chats.md`` — a single Markdown table. Running
this script parses that table and (re)writes the generated index files:

* ``README.md``        — overview, category table, tag cloud and links
* ``categories/*.md``  — one file per category
* ``tags.md``          — every tag with the chats that use it
* ``timeline.md``      — all chats in chronological order

Usage::

    uv run python knowledge-base/generate.py

The generated files carry a "do not edit by hand" banner; edit the source
table and re-run this script instead.
"""

from __future__ import annotations

import re
from collections import Counter
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DATA_FILE = ROOT / "data" / "chats.md"
CATEGORIES_DIR = ROOT / "categories"
ID_RE = re.compile(r"#\d+")
BANNER = (
    "<!-- GENERATED by generate.py — do not edit by hand. "
    "Edit data/chats.md and re-run `uv run python knowledge-base/generate.py`. -->"
)


@dataclass(frozen=True, slots=True)
class Chat:
    """A single archived conversation."""

    cid: str  # zero-padded id without the leading '#', e.g. "001"
    date: str  # ISO date, e.g. "2026-03-15"
    category: str
    title: str
    tags: tuple[str, ...]

    @property
    def label(self) -> str:
        return f"#{self.cid}"


def slugify(value: str) -> str:
    """Turn a category or tag name into a filesystem/anchor-safe slug."""
    text = value.lower().replace("+", " plus ").replace("&", " and ")
    text = re.sub(r"[^a-z0-9]+", "-", text)
    return text.strip("-")


def parse_cells(line: str) -> list[str]:
    """Split one Markdown table row into trimmed cell values."""
    return [cell.strip() for cell in line.strip().strip("|").split("|")]


def load_chats(path: Path) -> list[Chat]:
    """Parse the source Markdown table into a sorted list of chats."""
    if not path.exists():
        raise FileNotFoundError(f"Source table not found: {path}")
    chats: list[Chat] = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        if "|" not in raw:
            continue
        cells = parse_cells(raw)
        if len(cells) < 5 or not ID_RE.fullmatch(cells[0]):
            continue
        tags = tuple(tag.strip() for tag in cells[4].split(",") if tag.strip())
        chats.append(
            Chat(
                cid=cells[0].lstrip("#"),
                date=cells[1],
                category=cells[2],
                title=cells[3],
                tags=tags,
            )
        )
    if not chats:
        raise ValueError(f"No chat rows parsed from {path}")
    chats.sort(key=lambda chat: chat.cid)
    return chats


def category_slugs(chats: list[Chat]) -> dict[str, str]:
    """Map each category to a unique slug, disambiguating any collisions.

    Distinct categories can share a base slug (e.g. ``Mobile / Dev`` and
    ``Mobile Dev``); the second and later get a numeric suffix so every
    category keeps its own file. Order is stable (categories sorted by name).
    """
    slugs: dict[str, str] = {}
    used: set[str] = set()
    for category in sorted({chat.category for chat in chats}):
        base = slugify(category)
        slug = base
        suffix = 2
        while slug in used:
            slug = f"{base}-{suffix}"
            suffix += 1
        used.add(slug)
        slugs[category] = slug
    return slugs


def render_readme(chats: list[Chat], slugs: dict[str, str]) -> str:
    """Build the top-level README index."""
    cat_counts = Counter(chat.category for chat in chats)
    tag_counts = Counter(tag for chat in chats for tag in chat.tags)
    dates = sorted(chat.date for chat in chats)

    lines: list[str] = [
        BANNER,
        "",
        "# Knowledge Base — Chat Archive",
        "",
        (
            f"Structured archive of **{len(chats)} conversations** spanning "
            f"**{dates[0]} → {dates[-1]}**, across **{len(cat_counts)} "
            f"categories** and **{len(tag_counts)} tags**."
        ),
        "",
        "## Categories",
        "",
        "| Category | Chats |",
        "| --- | ---: |",
    ]
    for category, count in sorted(cat_counts.items(), key=lambda kv: (-kv[1], kv[0])):
        lines.append(f"| [{category}](categories/{slugs[category]}.md) | {count} |")

    lines += ["", "## Tags", "", "| Tag | Chats |", "| --- | ---: |"]
    for tag, count in sorted(tag_counts.items(), key=lambda kv: (-kv[1], kv[0])):
        lines.append(f"| [`{tag}`](tags.md#{slugify(tag)}) | {count} |")

    lines += [
        "",
        "## Indexes",
        "",
        "- [Timeline](timeline.md) — every chat in date order",
        "- [Tags](tags.md) — chats grouped by tag",
        "- [Categories](categories/) — one file per category",
        "- [Source table](data/chats.md) — the editable source of truth",
        "",
    ]
    return "\n".join(lines) + "\n"


def render_category(category: str, chats: list[Chat]) -> str:
    """Build one category index file."""
    rows = [chat for chat in chats if chat.category == category]
    lines: list[str] = [
        BANNER,
        "",
        f"# {category}",
        "",
        f"{len(rows)} chats.",
        "",
        "| # | Date | Title | Tags |",
        "| --- | --- | --- | --- |",
    ]
    for chat in rows:
        tags = ", ".join(f"`{tag}`" for tag in chat.tags)
        lines.append(f"| {chat.label} | {chat.date} | {chat.title} | {tags} |")
    lines += ["", "[← Back to index](../README.md)", ""]
    return "\n".join(lines) + "\n"


def render_tags(chats: list[Chat]) -> str:
    """Build the tag index file."""
    by_tag: dict[str, list[Chat]] = {}
    for chat in chats:
        for tag in chat.tags:
            by_tag.setdefault(tag, []).append(chat)

    lines: list[str] = [
        BANNER,
        "",
        "# Tags",
        "",
        f"{len(by_tag)} tags across {len(chats)} chats.",
        "",
    ]
    for tag in sorted(by_tag):
        rows = by_tag[tag]
        lines += [
            f"## `{tag}`",
            "",
            f"{len(rows)} chats.",
            "",
            "| # | Date | Category | Title |",
            "| --- | --- | --- | --- |",
        ]
        for chat in rows:
            lines.append(
                f"| {chat.label} | {chat.date} | {chat.category} | {chat.title} |"
            )
        lines.append("")
    lines += ["[← Back to index](README.md)", ""]
    return "\n".join(lines) + "\n"


def render_timeline(chats: list[Chat]) -> str:
    """Build the chronological index file."""
    rows = sorted(chats, key=lambda chat: (chat.date, chat.cid))
    lines: list[str] = [
        BANNER,
        "",
        "# Timeline",
        "",
        f"{len(rows)} chats in chronological order.",
        "",
        "| Date | # | Category | Title |",
        "| --- | --- | --- | --- |",
    ]
    lines.extend(
        f"| {chat.date} | {chat.label} | {chat.category} | {chat.title} |"
        for chat in rows
    )
    lines += ["", "[← Back to index](README.md)", ""]
    return "\n".join(lines) + "\n"


def main() -> None:
    chats = load_chats(DATA_FILE)
    slugs = category_slugs(chats)

    CATEGORIES_DIR.mkdir(exist_ok=True)
    for stale in CATEGORIES_DIR.glob("*.md"):
        stale.unlink()

    (ROOT / "README.md").write_text(render_readme(chats, slugs), encoding="utf-8")
    (ROOT / "tags.md").write_text(render_tags(chats), encoding="utf-8")
    (ROOT / "timeline.md").write_text(render_timeline(chats), encoding="utf-8")
    for category, slug in slugs.items():
        (CATEGORIES_DIR / f"{slug}.md").write_text(
            render_category(category, chats), encoding="utf-8"
        )

    print(f"Generated indexes for {len(chats)} chats across {len(slugs)} categories.")


if __name__ == "__main__":
    main()
